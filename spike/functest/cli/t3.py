from drive import *
import subprocess
# a run that finishes: the queue drains in order
m, log = mock(18103, [{"bash": "sleep 5; echo finished-work"}, {"text": "first done"}, {"text": "second request done"}, {"text": "rewind target"}])
a = App(args(18103, "--mode", "auto"))
a.wait(r"Full Auto")
a.send("start" + ENTER); a.wait(r"esc to stop")
a.send("steer with this" + ENTER); a.send("!echo from-the-queue" + ENTER); a.send("/rename Queued name" + ENTER); a.send("typing on")
check("all three queued", a.wait(r"◦ steer with this") and "⏵ !echo from" in a.term.screen() and "⏵ /rename" in a.term.screen(), a.term.screen())
check("message at the next step", a.wait(r"first done", 12, "all"), a.term.all())
req = [json.loads(l) for l in open(log)]
check("the model got it mid-run", any("steer with this" in r["users"] for r in req), req[-1]["users"])
check("commands after the run", a.wait(r"from-the-queue", 8, "all") and a.wait(r"Renamed\.", 8, "all"), a.term.all())
ti = a.term.all(); check("in the order typed", ti.index("from-the-queue") < ti.index("Renamed."), ti[-300:])
check("what's being typed survives", a.wait(r"› typing on"), a.term.screen())
check("sent nothing extra", len([json.loads(l) for l in open(log)]) == 2)
a.send("\x15"); a.pump(0.15)
a.send(ESC); a.pump(0.15); a.send(ESC); check("esc esc lists rewind points", a.wait(r"/rewind N goes back", 5, "all"), a.term.all()[-400:])
a.send("/rewind" + ENTER); a.wait(r"Requests", 3, "all")
a.send("/nosuch" + ENTER); check("unknown command when idle", a.wait(r"There's no /nosuch", 4), a.term.screen())
a.send("/exit" + ENTER); code = a.exit_code(); check("/exit", code == 0, f"code {code}")
check("restored after /exit", a.term.modes.get("?2004") is False, a.term.modes)
stop(m)
# the prompt on the command line
