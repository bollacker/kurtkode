from drive import *
md = "# Findings\n\nThe **parser** splits on `commas` and has a [doc](http://x.y).\n\n- first point\n- second point\n\n```python\nx = **not bold**\n```\nDone."
m, log = mock(18101, [{"text": md}, {"bash": "for i in 1 2 3 4 5 6; do echo line-$i; sleep 1; done; sleep 30"}, {"text": "after stop"}])
a = App(args(18101, "--mode", "auto"))
check("starts on the live screen", a.wait(r"› *\n.*pm/?model|model · Full Auto"), a.term.screen())
check("status line has model and mode", a.wait(r"model · Full Auto"), a.term.screen())
check("banner in place", "kurtkode" in a.term.all())
check("bracketed paste on", a.term.modes.get("?2004") is True)
a.send("Explain the parser"); check("typing echoes in the composer", a.wait(r"› Explain the parser"), a.term.screen())
a.send(ENTER)
check("reply rendered", a.wait(r"Done\.", where="all"), a.term.all())
t = a.term.all()
check("heading has no #", "Findings" in t and "# Findings" not in t, t)
check("bold markers gone", "The parser splits" in t and "**parser**" not in t, t)
check("code span unticked", "`commas`" not in t, t)
check("link shown with url", "doc (http://x.y)" in t, t)
check("bullets", "• first point" in t, t)
check("code keeps its text", "x = **not bold**" in t and "```" not in t, t)
check("prompt echoed to scrollback", "› Explain the parser" in t, t)
a.wait(r"\$0\.", 3)
check("cost in status", re.search(r"[≈]?\$0\.\d+", a.term.screen()), a.term.screen())
check("composer empty again", re.search(r"^› *$", a.term.screen(), re.M), a.term.screen())
# a long command, typing during it
a.send("Run the slow check" + ENTER)
check("run line with activity", a.wait(r"Run for i in 1 2 3.*esc to stop"), a.term.screen())
check("live tail of output", a.wait(r"line-3"), a.term.screen())
a.send("also look at the tests" + ENTER); check("message queued", a.wait(r"◦ also look at the tests"), a.term.screen())
a.send("!echo hi" + ENTER); check("command queued", a.wait(r"⏵ !echo hi"), a.term.screen())
a.send("/nosuch" + ENTER); check("unknown command refused during a run", a.wait(r"There's no /nosuch"), a.term.screen())
check("refused text back in the composer", a.wait(r"› /nosuch"), a.term.screen())
a.send("\x15"); a.pump(0.1)  # Ctrl-U
a.send("/context" + ENTER); check("info command answers during a run", a.wait(r"Context: about"), a.term.screen())
check("queue kept", "◦ also look" in a.term.screen(), a.term.screen())
a.send(UP); check("up takes the last queued back", a.wait(r"› !echo hi"), a.term.screen())
check("taken off the queue", "⏵ !echo hi" not in a.term.screen(), a.term.screen())
a.send(ENTER); check("queued again", a.wait(r"⏵ !echo hi"), a.term.screen())
a.send(ESC); check("esc stops the run", a.gone(r"esc to stop"), a.term.screen())
check("stopped run returns the queue to the draft", a.wait(r"› also look at the tests"), a.term.screen())
check("draft holds the command too", a.wait(r"!echo hi"), a.term.screen())
a.send(CTRLC); a.pump(0.2)
check("ctrl-c clears the draft first", re.search(r"^› *$", a.term.screen(), re.M), a.term.screen())
a.send(CTRLC); check("then says how to quit", a.wait(r"Ctrl-C again to quit"), a.term.screen())
a.send(CTRLC)
code = a.exit_code()
check("two ctrl-c quit", code in (130, 0), code)
check("terminal restored", a.term.modes.get("?2004") is False, a.term.modes)
stop(m); summary()
