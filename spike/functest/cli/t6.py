from drive import *
q3 = {"questions": [
  {"question": "Which database?", "header": "Storage", "options": [{"label": "SQLite", "description": "Nothing to run."}, {"label": "Postgres", "description": "A server to keep up."}]},
  {"question": "Which features?", "header": "Features", "multiple": True, "options": [{"label": "Auth"}, {"label": "Search"}, {"label": "Export"}]},
  {"question": "What's it called?"}]}
m, log = mock(18131, [{"tool": "ask_user", "args": q3}, {"text": "Got it, thanks."}, {"tool": "ask_user", "args": {"question": "Flat?", "options": ["Yes", "No"]}}, {"text": "Flat done."},
                      {"tool": "ask_user", "args": q3}, {"text": "Skipped done."}, {"tool": "ask_user", "args": {"question": "Pick?", "options": ["Red", "Green"]}}, {"text": "Words done."}])
a = App(args(18131, "--mode", "ask"))
check("starts", a.wait(r"Ask"), a.term.screen()); time.sleep(1); a.pump(0.2)
a.send("set it up" + ENTER)
check("first question", a.wait(r"\[Storage\] Which database\?  \(1 of 3\)"), a.term.screen())
check("list shows options", a.wait(r"1\. SQLite \(recommended\)  Nothing to run\."), a.term.screen())
check("hint", "enter answer" in a.term.screen() and "space select" not in a.term.screen(), a.term.screen())
time.sleep(0.6)
a.send(DOWN); a.pump(0.2); a.send(ENTER)
check("second question", a.wait(r"\[Features\] Which features\?  \(2 of 3\)"), a.term.screen())
check("scrollback has the pick", "→ Postgres" in a.term.all(), a.term.all())
check("tick boxes", a.wait(r"1\. \[ \] Auth"), a.term.screen())
time.sleep(0.6)
a.send(" "); a.pump(0.1); a.send(DOWN); a.pump(0.1); a.send(DOWN); a.pump(0.1); a.send(" "); a.pump(0.2)
check("two ticked", a.wait(r"3\. \[x\] Export") and "1. [x] Auth" in a.term.screen(), a.term.screen())
a.send(ENTER)
check("third question", a.wait(r"What's it called\?  \(3 of 3\)"), a.term.screen())
check("open question has no list", "1. " not in a.term.screen().split("What's it called")[-1], a.term.screen())
a.send("zephyr" + ENTER)
check("run finishes", a.wait(r"Got it, thanks\.", where="all"), a.term.all())
a.send("next" + ENTER)
check("flat form works", a.wait(r"\? Flat\?"), a.term.screen())
check("flat list", a.wait(r"1\. Yes \(recommended\)"), a.term.screen())
time.sleep(0.6); a.send("2" + ENTER)
check("number still works", a.wait(r"Flat done\.", where="all"), a.term.all())
a.send("again" + ENTER)
check("batch again", a.wait(r"\(1 of 3\)"), a.term.screen())
time.sleep(0.6); a.send(ESC)
check("esc skips all", a.wait(r"Skipped done\.", where="all"), a.term.all())
a.send("words" + ENTER)
check("pick question", a.wait(r"\? Pick\?"), a.term.screen())
time.sleep(0.6); a.send("neither of these" + ENTER)
check("words answer", a.wait(r"Words done\.", where="all"), a.term.all())
a.send("/exit" + ENTER); a.exit_code(); stop(m)
text = "\n".join(str(json.loads(l).get("last")) for l in open(log))
check("batch answers reached the model", all(x in text for x in ["Which database? → Postgres", "Which features? → Auth; Export", "What's it called? → zephyr"]), text[-1500:])
check("flat answer", "The user answered: No" in text, text[-800:])
check("skip", "The user chose not to answer" in text, text[-800:])
check("words", "The user answered: neither of these" in text, text[-800:])
summary()
