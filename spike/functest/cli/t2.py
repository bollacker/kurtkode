from drive import *
if os.path.exists(HERE + "/proj/new.txt"): os.remove(HERE + "/proj/new.txt")      # a rerun in the same folder
open(HERE + "/proj/parser.py", "w").write("# for path completion\n")
long_paste = "\n".join(f"trace {i}" for i in range(1, 31))
script = [
 {"bash": "echo approved-$((40+2))"}, {"text": "ran it"},
 {"tool": "write_file", "args": {"path": "new.txt", "content": "alpha\nbeta\n"}}, {"text": "wrote it"},
 {"text": "got the paste"}, {"text": "retried reply"}, {"text": "plain reply"},
]
m, log = mock(18102, script)
a = App(args(18102, "--mode", "ask"))
a.wait(r"model · Ask")
a.send("run something" + ENTER)
check("approval card shown", a.wait(r"\[y\] yes.*\[n\] no"), a.term.screen())
check("question replaces the prompt", a.wait(r"^  › *$", 3), a.term.screen())
check("says it's waiting", "waiting for your answer" in a.term.screen() and "esc to stop" not in a.term.screen(), a.term.screen())
a.send("half typed")  # goes to the answer
a.send("\x15")
a.send(ENTER); check("an empty Enter doesn't approve", a.wait(r"y or n ›"), a.term.screen())
check("nothing ran yet", "approved-42" not in a.term.all(), a.term.all())
a.send("y" + ENTER)
check("approved command ran", a.wait(r"approved-42", where="all"), a.term.all())
a.wait(r"ran it", where="all"); a.gone(r"esc to stop")
a.send(STAB); check("shift-tab: edits", a.wait(r"model · Accept Edits"), a.term.screen())
a.send(STAB); check("shift-tab: plan", a.wait(r"model · Plan"), a.term.screen())
a.send(STAB); check("shift-tab: auto", a.wait(r"model · Full Auto"), a.term.screen())
a.send("write a file" + ENTER)
check("a write shows its diff", a.wait(r"\+alpha", where="all"), a.term.all())
a.wait(r"wrote it", where="all"); a.gone(r"esc to stop")
check("the file is there", os.path.exists(HERE + "/proj/new.txt"))
a.send(CTRLO); check("ctrl-o shows the last output", a.wait(r"alpha", where="all"))
a.send(UP); check("up recalls the last prompt", a.wait(r"› write a file"), a.term.screen())
a.send(UP); check("further back", a.wait(r"› run something"), a.term.screen())
a.send(DOWN); a.send(DOWN); check("down returns to an empty draft", a.wait(r"^› *$"), a.term.screen())
a.send(CTRLR); a.send("run"); check("ctrl-r searches", a.wait(r"search: run → run something"), a.term.screen())
a.send(ENTER); check("search takes the match", a.wait(r"› run something"), a.term.screen())
a.send("\x15")
a.send("/co"); check("slash completion list", a.wait(r"compact") and "context" in a.term.screen(), a.term.screen())
a.send(TAB); check("tab fills it", a.wait(r"› /compact"), a.term.screen())
a.send("\x15"); a.gone(r"^  compact")
a.send("look at @par"); check("path completion", a.wait(r"parser\.py"), a.term.screen())
a.send(TAB); check("path filled", a.wait(r"@parser\.py"), a.term.screen())
a.send("\x15")
a.send("\x1b[200~" + long_paste + "\x1b[201~"); check("long paste becomes a token", a.wait(r"\[Pasted text #1: 30 lines\]"), a.term.screen())
check("paste note", "30 lines pasted" in a.term.screen(), a.term.screen())
a.send(" see this" + ENTER)
check("reply to paste", a.wait(r"got the paste", where="all"), a.term.all())
a.gone(r"esc to stop")
last = [json.loads(l) for l in open(log)][-1]
check("the paste reached the model whole", "trace 30" in last["last"] and "Pasted text" not in last["last"], last["last"][:200])
t = a.term.all(); check("echo folds a long message", "more lines" in t, t[-500:])
a.send("one\\" + ENTER + "two"); check("backslash continues", a.wait(r"one\n +two"), a.term.screen())
a.send("\x15\x15"); a.send("\x7f"); a.pump(0.1); a.send("\x15")
a.send("/status" + ENTER); check("/status", a.wait(r"Mode +Full Auto", where="all") and "Spent" in a.term.all(), a.term.screen())
a.send("/rename Parser work" + ENTER); check("/rename", a.wait(r"Renamed\.", where="all"), a.term.screen())
a.send("/retry" + ENTER); check("/retry", a.wait(r"retried reply", where="all"), a.term.screen())
a.gone(r"esc to stop")
a.send("/export out.md" + ENTER); check("/export", a.wait(r"Saved ", where="all"), a.term.screen())
check("export written", "retried reply" in open(HERE + "/proj/out.md").read())
a.send("/resume" + ENTER); check("/resume lists", a.wait(r"Parser work.*this one", where="all"), a.term.screen())
a.send("/help" + ENTER); check("/help has the new commands", a.wait(r"/status  Show", where="all") and "/exit" in a.term.all())
a.send("!echo shell-out" + ENTER); check("! runs", a.wait(r"shell-out", where="all"), a.term.screen())
a.send("# the parser is simple" + ENTER); check("# remembers", a.wait(r"Remembered", where="all"), a.term.screen())
a.resize(20, 60); a.send("x"); check("works after a resize", a.wait(r"› x"), a.term.screen())
check("no row reaches the last column", all(len(r.rstrip()) < 60 for r in a.term.screen().split("\n")[-2:]), a.term.screen())
a.send("\x7f"); a.send(CTRLD)
check("ctrl-d quits", a.exit_code() == 0)
check("restored", a.term.modes.get("?2004") is False, a.term.modes)
# small terminal, a long multi-line draft
b = App(args(18102, "--mode", "auto"), rows=8, cols=40)
b.wait(r"Full Auto")
b.send("\n".join(f"row {i}" for i in range(12)).replace("\n", "\x0a"))
b.pump(0.3)
s = b.term.screen(); check("a tall draft fits a short terminal", "row 11" in s and len(s.split("\n")) <= 8, s)
check("caret on the last text row", b.term.r <= 7 and "row 11" in "".join(b.term.grid[b.term.r]), (b.term.r, s))
b.send("\x03\x03"); b.pump(0.2); b.send("\x03"); b.exit_code()
stop(m); summary()
